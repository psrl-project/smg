#[test]
fn tools_key_order_change_must_invalidate_render_context_hash() {
    // Regression test for the stale-prefix bug: the render_context hash used to
    // canonicalize (sort) tools, but the chat template renders `tools | tojson`
    // in native key order.  A request whose tools JSON key order changes between
    // turns therefore re-used a stale prefix whose rendered system header
    // diverged from the current render (the validator's `non_assistant_text`
    // position-1 error).  The hash must be order-sensitive.
    let tools_a = vec![json!({
        "type": "function",
        "function": {
            "name": "Bash",
            "parameters": {
                "type": "object",
                "properties": {
                    "command": {"type": "string"},
                    "timeout": {"type": "number"},
                    "description": {"type": "string"}
                },
                "required": ["command"]
            }
        }
    })];
    let tools_b = vec![json!({
        "type": "function",
        "function": {
            "name": "Bash",
            "parameters": {
                "type": "object",
                "properties": {
                    "description": {"type": "string"},
                    "timeout": {"type": "number"},
                    "command": {"type": "string"}
                },
                "required": ["command"]
            }
        }
    })];

    let ctx_a = RenderContext::new(Some(tools_a), None);
    let ctx_b = RenderContext::new(Some(tools_b), None);
    let messages = vec![ChatMessage::System {
        content: MessageContent::Text("You are a coding agent.".to_string()),
        name: None,
    }];

    let hash_a = hash_messages_with_context(&messages, &ctx_a);
    let hash_b = hash_messages_with_context(&messages, &ctx_b);
    assert_ne!(
        hash_a, hash_b,
        "tools key-order change must invalidate the render_context hash"
    );

    // And the renders must differ accordingly (native order preserved).
    let Some(tokenizer) = load_qwen3_tokenizer(None) else {
        eprintln!("SKIP: real Qwen3 tokenizer not found");
        return;
    };
    let text_a = render(&*tokenizer, &messages, &ctx_a, false);
    let text_b = render(&*tokenizer, &messages, &ctx_b, false);
    assert_ne!(
        text_a, text_b,
        "tools key-order must change the rendered header"
    );
}

#[test]
fn real_qwen35_compressed_context_uses_whole_slice_path() {
    // Qwen3.5's stock template is position-dependent: an assistant turn is
    // wrapped in `<think>` only when it appears after the last real user query
    // (`ns.last_query_index`).  The engine must therefore take the whole-slice
    // single-pass path (`[dummy_system, dummy_user]` base) instead of per-message
    // dummy bases.  The whole-slice path is translation-invariant: the appended
    // messages render with the same wrap/tool decisions as the production
    // context, for BOTH the stock template and the patched position-independent
    // one.  This test runs against the stock template and verifies the merged
    // incremental byte-for-byte against the production slice render.
    //
    // Note: the TITO validator cannot be used here — the stock template
    // re-evaluates the `<think>` wrap of past turns from the final message
    // list, so the accumulated stream and a one-shot render never align.
    let Some(tokenizer) = load_qwen35_tokenizer() else {
        eprintln!("SKIP: real Qwen3.5 tokenizer not found");
        return;
    };
    let ctx = render_context();
    let adapter = select_adapter_for_tokenizer(&*tokenizer).unwrap();
    assert!(
        tokenizer.chat_template_is_position_dependent(),
        "stock Qwen3.5 template must use the whole-slice path"
    );

    let store = TitoStore::new();
    store.create_session("s1");

    let system = ChatMessage::System {
        content: MessageContent::Text("You are a coding agent.\nSolve the task.".to_string()),
        name: None,
    };
    let user1 = user_msg("Inspect the repo.");
    let (turn0_full, assistant1) = simulate_generation(
        &*tokenizer,
        &[system.clone(), user1.clone()],
        &ctx,
        "Let me look around.",
    );
    store
        .store(
            "s1",
            &[system.clone(), user1.clone(), assistant1.clone()],
            turn0_full.clone(),
            record(turn0_full.len()),
            &ctx,
            0,
        )
        .unwrap();

    let turn2_req = vec![
        system.clone(),
        user1.clone(),
        assistant1.clone(),
        assistant_msg("I checked the failing test."),
        tool_msg("tests: 1 failed", "call_1"),
        user_msg("Fix the failing test."),
        assistant_msg("(compacted plan: patch the assertion)"),
    ];
    let lookup = store
        .find_prefix_with_lookup("s1", &turn2_req, &ctx)
        .unwrap();
    let pm = lookup.matched.expect("expected a prefix HIT");
    assert_eq!(pm.matched_message_num, 3);
    let appended = &turn2_req[pm.matched_message_num..];
    assert!(appended
        .iter()
        .any(|m| matches!(m, ChatMessage::Assistant { .. })));
    let stored_prefix_ids = pm.pretokenized_ids.clone();

    let merged =
        TitoEngine::merge_incremental(pm, appended, &*tokenizer, &*adapter, &ctx, None).unwrap();

    // The whole-slice incremental (after the adjusted prefix) must equal the
    // production render of the appended slice (+ the generation prompt)
    // relative to the user prefix — under the stock position-dependent template.
    let mut prod_all = vec![system.clone(), user1.clone()];
    prod_all.extend_from_slice(appended);
    let prod_base_text = render(&*tokenizer, &[system.clone(), user1.clone()], &ctx, false);
    let prod_full_text = render(&*tokenizer, &prod_all, &ctx, true);
    assert!(prod_full_text.starts_with(&prod_base_text));
    let prod_tail = &prod_full_text[prod_base_text.len()..];

    let adjusted_prefix = adapter.adjust_prefix_boundary(&stored_prefix_ids);
    let incremental_ids = &merged[adjusted_prefix.len()..];
    let incremental_text = decode(&*tokenizer, incremental_ids);
    assert_eq!(
        incremental_text, prod_tail,
        "whole-slice incremental must equal the production slice render"
    );
}

