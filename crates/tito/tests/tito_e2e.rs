/// Load the real Qwen3.5 tokenizer with its own (position-dependent) chat template.
fn load_qwen35_tokenizer() -> Option<Arc<dyn Tokenizer>> {
    let dir = real_qwen35_dir()?;
    create_tokenizer_with_chat_template(&dir, None).ok()
}

/// Load the real Qwen3.5 tokenizer with an explicit template (e.g. the patched
/// position-independent one).  SMG does not own model-specific template patches;
/// the deployment layer supplies them via `chat_template_path`, which the test
/// mirrors by staging the template to a temp file.
fn load_qwen35_tokenizer_with_template(template: &str) -> Option<Arc<dyn Tokenizer>> {
    let dir = real_qwen35_dir()?;
    let mut f = tempfile::NamedTempFile::new().ok()?;
    std::io::Write::write_all(&mut f, template.as_bytes()).ok()?;
    create_tokenizer_with_chat_template(&dir, f.path().to_str()).ok()
}

fn render(
    tokenizer: &dyn Tokenizer,
    messages: &[ChatMessage],
    ctx: &RenderContext,
    add_generation_prompt: bool,
) -> String {
    // All test messages use plain-text content, so no content-field transform
    // is needed; serialize each message directly.
    let values: Vec<serde_json::Value> = messages
        .iter()
        .map(|m| serde_json::to_value(m).unwrap())
        .collect();
    tokenizer
        .apply_chat_template(
            &values,
            ChatTemplateParams {
                add_generation_prompt,
                tools: ctx.tools_ref(),
                template_kwargs: ctx.template_kwargs_ref(),
                ..Default::default()
            },
        )
        .unwrap()
}

fn encode(tokenizer: &dyn Tokenizer, text: &str) -> Vec<u32> {
    tokenizer.encode(text, false).unwrap().token_ids().to_vec()
}

fn decode(tokenizer: &dyn Tokenizer, ids: &[u32]) -> String {
    tokenizer.decode(ids, false).unwrap()
}

fn user_msg(content: &str) -> ChatMessage {
    ChatMessage::User {
        content: MessageContent::Text(content.to_string()),
        name: None,
    }
}

fn assistant_msg(content: &str) -> ChatMessage {
    ChatMessage::Assistant {
        content: Some(MessageContent::Text(content.to_string())),
        name: None,
        tool_calls: None,
        reasoning_content: None,
    }
}

fn assistant_tool_call_msg(
    content: Option<&str>,
    tool_call_id: &str,
    fn_name: &str,
) -> ChatMessage {
    use openai_protocol::common::{FunctionCallResponse, ToolCall};
    ChatMessage::Assistant {
        content: content.map(|c| MessageContent::Text(c.to_string())),
        name: None,
        reasoning_content: None,
        tool_calls: Some(vec![ToolCall {
            id: tool_call_id.to_string(),
            tool_type: "function".to_string(),
            function: FunctionCallResponse {
                name: fn_name.to_string(),
                arguments: Some("{}".to_string()),
            },
        }]),
    }
}

fn tool_msg(content: &str, call_id: &str) -> ChatMessage {
    ChatMessage::Tool {
        content: MessageContent::Text(content.to_string()),
        tool_call_id: call_id.to_string(),
    }
}

fn record(prompt_token_count: usize) -> TurnRecord {
    TurnRecord {
        prompt_token_count,
        output_logprobs: None,
        finish_reason: "stop".to_string(),
        mismatch_report: vec![],
        routed_experts: None,
        weight_version: None,
    }
}

fn render_context() -> RenderContext {
    RenderContext::new(None, None)
}

/// Validate that no TITO violation (non-assistant / structural mismatch) exists
/// between the merged token stream and the canonical full render.
fn assert_no_tito_violation(
    tokenizer: &Arc<dyn Tokenizer>,
    full_ids: &[u32],
    all_messages: &[ChatMessage],
    ctx: &RenderContext,
    adapter: &dyn ModelAdapter,
    label: &str,
) {
    let special: std::collections::HashSet<u32> =
        adapter.trailing_token_ids().iter().copied().collect();
    let validator = TokenSeqValidator::new(
        Arc::clone(tokenizer),
        adapter.assistant_start_str().map(String::from),
        special,
    );
    let mismatches = validator.validate(full_ids, all_messages, false, None, ctx);
    let violations: Vec<_> = mismatches
        .iter()
        .filter(|m| m.mismatch_type != "assistant_text")
        .collect();
    assert!(
        violations.is_empty(),
        "[{label}] TITO violations detected: {violations:#?}",
    );
}

/// Simulate one generation turn: returns the `full_ids` (prompt + output) that
/// production would store, plus the assistant message that gets hashed into the
/// prefix tree.
///
/// The model generates after the generation prompt and terminates its turn with
/// the EOS `<|im_end|>` token, so `output_text` is encoded with a trailing
/// `<|im_end|>` (mirroring the raw output stored in the accumulated sequence).
fn simulate_generation(
    tokenizer: &dyn Tokenizer,
    request_messages: &[ChatMessage],
    ctx: &RenderContext,
    output_text: &str,
) -> (Vec<u32>, ChatMessage) {
    let prompt_ids = encode(tokenizer, &render(tokenizer, request_messages, ctx, true));
    let output_ids = encode(tokenizer, &format!("{output_text}<|im_end|>"));
    let mut full_ids = prompt_ids;
    full_ids.extend_from_slice(&output_ids);
    (full_ids, assistant_msg(output_text))
}

/// Assistant message carrying a separate reasoning (`<think>`) block.
fn assistant_reasoning_msg(think: &str, answer: &str) -> ChatMessage {
    ChatMessage::Assistant {
        content: Some(MessageContent::Text(answer.to_string())),
        name: None,
        reasoning_content: Some(think.to_string()),
        tool_calls: None,
    }
}

/// Simulate a thinking-model generation turn: the model continues the
/// generation prompt's `<think>` prefill, writes its reasoning, closes
/// `</think>`, then answers and emits `<|im_end|>`.
fn simulate_generation_thinking(
    tokenizer: &dyn Tokenizer,
    request_messages: &[ChatMessage],
    ctx: &RenderContext,
    think: &str,
    answer: &str,
) -> (Vec<u32>, ChatMessage) {
    let prompt_ids = encode(tokenizer, &render(tokenizer, request_messages, ctx, true));
    let output_ids = encode(
        tokenizer,
        &format!("{think}\n</think>\n\n{answer}<|im_end|>"),
    );
    let mut full_ids = prompt_ids;
    full_ids.extend_from_slice(&output_ids);
    (full_ids, assistant_reasoning_msg(think, answer))
}

#[test]
fn real_qwen3_multiturn_merge_matches_full_render() {
    let Some(tokenizer) = load_qwen3_tokenizer(None) else {
        eprintln!("SKIP: real Qwen3 tokenizer not found");
        return;
    };
    let ctx = render_context();
    let adapter = select_adapter_for_tokenizer(&*tokenizer).unwrap();
    let store = TitoStore::new();
    store.create_session("s1");

    let system = ChatMessage::System {
        content: MessageContent::Text("You are a coding agent.\nSolve the task.".to_string()),
        name: None,
    };
    let user1 = user_msg("Inspect the repo.");
    let turn0_req = vec![system.clone(), user1.clone()];
    let (turn0_full, assistant1) =
        simulate_generation(&*tokenizer, &turn0_req, &ctx, "Let me look around.");
    store
        .store(
            "s1",
            &[system.clone(), user1.clone(), assistant1.clone()],
            turn0_full.clone(),
            record(turn0_full.len()),
            &ctx,
            0,
        )
        .unwrap();

    let turn1_req = vec![
        system.clone(),
        user1.clone(),
        assistant1.clone(),
        tool_msg("repo has src/main.py", "call_1"),
        user_msg("Fix the bug in src/main.py."),
    ];
    let lookup = store
        .find_prefix_with_lookup("s1", &turn1_req, &ctx)
        .unwrap();
    let pm = lookup.matched.expect("expected a prefix HIT on turn 1");
    assert_eq!(pm.matched_message_num, 3);

    let appended = &turn1_req[pm.matched_message_num..];
    let merged =
        TitoEngine::merge_incremental(pm, appended, &*tokenizer, &*adapter, &ctx, None).unwrap();

    let mut full_ids = merged;
    full_ids.extend(encode(
        &*tokenizer,
        "I found the bug and fixed it.<|im_end|>",
    ));

    let mut all_messages = turn1_req;
    all_messages.push(assistant_msg("I found the bug and fixed it."));
    assert_no_tito_violation(
        &tokenizer,
        &full_ids,
        &all_messages,
        &ctx,
        &*adapter,
        "multi-turn",
    );
}

