#[test]
fn qwen35_patched_template_is_position_independent() {
    // Load the patched Qwen3.5 template explicitly (PSRL side supplies it via
    // `chat_template_path`; SMG does not own model-specific patches).  Verify
    // the core property of Plan A: appending a later user query after an
    // assistant turn must NOT change how that assistant renders (the stock
    // template would re-evaluate its `<think>` wrap and strip it).
    let Some(tokenizer) = load_qwen35_tokenizer_with_template(QWEN35_NO_THINK_STRIP_TEMPLATE)
    else {
        eprintln!("SKIP: real Qwen3.5 tokenizer not found");
        return;
    };
    let ctx = render_context();

    let system = ChatMessage::System {
        content: MessageContent::Text("You are a coding agent.\nSolve the task.".to_string()),
        name: None,
    };
    let user1 = user_msg("Inspect the repo.");
    let assistant = assistant_reasoning_msg("I should inspect.", "Let me look around.");

    let before = vec![system.clone(), user1.clone(), assistant.clone()];
    let after = vec![
        system.clone(),
        user1.clone(),
        assistant.clone(),
        user_msg("Now fix it."),
    ];
    let before_text = render(&*tokenizer, &before, &ctx, false);
    let after_text = render(&*tokenizer, &after, &ctx, false);
    assert!(
        after_text.starts_with(&before_text),
        "patched template must render the assistant identically regardless of position"
    );
    // The assistant's reasoning block must be present in both renders.
    assert!(before_text.contains("<think>"));
}
