fn real_qwen3_dir() -> Option<String> {
    let candidates = [
        std::env::var("SMG_QWEN3_TOKENIZER_DIR").ok(),
        Some(
            "/dev/shm/verl-cache/142bc806fb2a1653e8221c7bedce85e4/Qwen3-4B-Instruct-2507"
                .to_string(),
        ),
    ];
    candidates
        .into_iter()
        .flatten()
        .find(|p| Path::new(p).join("tokenizer.json").exists())
}

/// Load the real Qwen3 tokenizer. `template_override`: if `Some`, the template
/// text is written to a temp file and passed as the chat template; if `None`,
/// the model's own chat template (from tokenizer_config.json) is used.
fn load_qwen3_tokenizer(template_override: Option<&str>) -> Option<Arc<dyn Tokenizer>> {
    let dir = real_qwen3_dir()?;
    let template_path = match template_override {
        Some(template) => {
            let mut f = tempfile::NamedTempFile::new().ok()?;
            std::io::Write::write_all(&mut f, template.as_bytes()).ok()?;
            Some(f.path().to_str().unwrap().to_string())
        }
        None => None,
    };
    create_tokenizer_with_chat_template(&dir, template_path.as_deref()).ok()
}

