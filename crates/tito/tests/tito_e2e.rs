//! End-to-end TITO merge tests against a **real** tokenizer.
//!
//! These tests load actual Qwen3 / Qwen3.5 tokenizers (the models used by the
//! mini-SWE PSRL runs) and verify that the incremental merge produced by
//! [`smg_tito::engine::TitoEngine`] — including multi-turn interleaving and the
//! compacted-context case where assistant turns appear in the appended slice —
//! is byte-correct with respect to the chat template's full one-shot render.
//!
//! The tokenizer directories are resolved from `SMG_QWEN3_TOKENIZER_DIR` /
//! `SMG_QWEN35_TOKENIZER_DIR`, falling back to the verl-cache locations present
//! on the training hosts.  If neither exists the tests are skipped (they are not
//! part of a hermetic CI build).

